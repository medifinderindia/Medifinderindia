assert.match(ui,/delivery:Math\.max\(0,Number\(serviceability&&serviceability\.baseFee\)\|\|0\)/);
assert.match(rules,/base_fee/);
assert.match(rules,/\.or\("pin\.eq\."\+p\+",pincode\.eq\."\+p\)/);
console.log("PASS: COD SQL security, seller/PIN validation, row locking, atomic stock decrement, idempotency, RX pharmacy acceptance and final fee/notification contract");
