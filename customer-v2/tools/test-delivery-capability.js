"use strict";
const assert = require("node:assert/strict");
const fs = require("node:fs");
const vm = require("node:vm");
const source = fs.readFileSync(require("node:path").join(__dirname, "..", "delivery-capability.js"), "utf8");
const window = {};
vm.runInNewContext(source, { window, Object });
assert.equal(typeof window.MFCustomerV2DeliveryCapability.resolve, "function");
const missing = window.MFCustomerV2DeliveryCapability.resolve(null);
assert.equal(missing.status, "unknown");
assert.equal(missing.available, false);
const rejected = window.MFCustomerV2DeliveryCapability.resolve({ available: false, pincode: "733140" });
assert.equal(rejected.status, "unknown");
assert.equal(rejected.available, false);
const zoneOnly = window.MFCustomerV2DeliveryCapability.resolve({ available: true, pincode: "733140" });
assert.equal(zoneOnly.status, "unknown");
assert.equal(zoneOnly.available, false);
assert.match(zoneOnly.reason, /capacity/i);
console.log("Delivery capability fail-closed tests passed.");
